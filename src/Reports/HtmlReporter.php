<?php

declare(strict_types=1);

namespace LaraInspect\Reports;

use LaraInspect\Contracts\ReporterInterface;
use LaraInspect\Model\AnalyzerResult;
use LaraInspect\Model\Confidence;
use LaraInspect\Model\Finding;
use LaraInspect\Model\InspectionReport;
use LaraInspect\Model\ResultStatus;
use LaraInspect\Model\Table;

/**
 * Single self-contained HTML file: no external scripts, fonts or stylesheets,
 * so it can be opened offline and attached to tickets. All content is escaped.
 */
final class HtmlReporter implements ReporterInterface
{
    public function format(): string
    {
        return 'html';
    }

    public function fileExtension(): string
    {
        return 'html';
    }

    public function render(InspectionReport $report): string
    {
        $findings = $report->findings();

        $meta = '';
        foreach (ReportSummary::metadata($report) as [$label, $value]) {
            $meta .= sprintf('<dt>%s</dt><dd>%s</dd>', self::e($label), self::e($value));
        }

        $warnings = '';
        foreach ($report->project->warnings as $warning) {
            $warnings .= sprintf('<p class="callout warn">%s</p>', self::e($warning));
        }

        $counts = '';
        foreach ($report->severityCounts() as $severity => $count) {
            $counts .= sprintf(
                '<div class="count sev-%s%s"><span class="n">%d</span><span class="l">%s</span></div>',
                strtolower($severity),
                $count === 0 ? ' zero' : '',
                $count,
                self::e($severity),
            );
        }

        $nav = '<a href="#summary">Summary</a>';
        if ($findings !== []) {
            $nav .= '<a href="#findings">Findings</a>';
        }
        foreach ($report->results as $result) {
            $nav .= sprintf('<a href="#section-%s">%s</a>', self::e($result->analyzer), self::e($result->title));
        }
        if ($report->insights !== []) {
            $nav .= '<a href="#ai">AI analysis</a>';
        }
        if ($report->audit !== []) {
            $nav .= '<a href="#operations">Operations</a>';
        }

        $findingsHtml = '';
        if ($findings !== []) {
            $findingsHtml = '<section id="findings"><h2>Findings</h2>';
            foreach ($findings as $i => $finding) {
                $findingsHtml .= $this->finding($finding, $i + 1);
            }
            $findingsHtml .= '</section>';
        }

        $sections = '';
        foreach ($report->results as $result) {
            $sections .= $this->section($result);
        }

        $ai = '';
        if ($report->insights !== []) {
            $ai = '<section id="ai" class="ai"><h2>AI-assisted analysis <span class="badge ai-badge">AI-generated</span></h2>'
                . '<p class="callout warn">Written by a language model from the redacted inspection results above. It can be wrong, and it does not replace the deterministic findings. Verify recommendations before acting on them.</p>';
            foreach ($report->insights as $insight) {
                $ai .= sprintf('<article class="insight"><h3>%s</h3><p class="where">%s · %s · %s</p>', self::e($insight->title), self::e($insight->provider), self::e($insight->model), self::e($insight->usage->describe()));
                if ($insight->error !== null) {
                    $ai .= sprintf('<p class="callout">Not available: %s</p>', self::e($insight->error));
                }
                if ($insight->content !== '') {
                    $ai .= sprintf('<div class="ai-text">%s</div>', self::e($insight->content));
                }
                foreach ($insight->notes as $note) {
                    $ai .= sprintf('<p class="callout">%s</p>', self::e($note));
                }
                $ai .= '</article>';
            }
            $ai .= '</section>';
        }

        $operations = '';
        if ($report->audit !== []) {
            $rows = [];
            foreach ($report->audit as $entry) {
                $rows[] = [
                    $entry->timestamp,
                    $entry->purpose,
                    $entry->command,
                    $entry->outcome . ($entry->exitCode !== null ? ' (exit ' . $entry->exitCode . ')' : ''),
                    $entry->network ? 'yes' : 'no',
                ];
            }
            $operations = '<section id="operations"><h2>Operations</h2><p>External commands run during this inspection.</p>'
                . $this->table(new Table('', ['Time', 'Purpose', 'Command', 'Outcome', 'Network'], $rows), codeColumn: 2)
                . '</section>';
        }

        $generator = self::e($report->inspectorVersion);
        $title = self::e('Inspection: ' . $report->project->name);
        $verdict = self::e(ReportSummary::verdict($report));
        $readOnly = self::e(ReportSummary::readOnlyStatement());
        $footer = self::e(sprintf(
            'Generated by Laravel Project Inspector %s on %s.',
            $report->inspectorVersion,
            $report->generatedAt->format(\DateTimeInterface::ATOM),
        ));
        $css = self::CSS;

        return <<<HTML
            <!doctype html>
            <html lang="en">
            <head>
            <meta charset="utf-8">
            <meta name="viewport" content="width=device-width, initial-scale=1">
            <meta name="generator" content="Laravel Project Inspector {$generator}">
            <title>{$title}</title>
            <style>{$css}</style>
            </head>
            <body>
            <header>
            <h1>{$title}</h1>
            <p class="lede">{$readOnly}</p>
            <dl class="meta">{$meta}</dl>
            </header>
            <nav>{$nav}</nav>
            <main>
            {$warnings}
            <section id="summary">
            <h2>Summary</h2>
            <p class="verdict">{$verdict}</p>
            <div class="counts">{$counts}</div>
            </section>
            {$findingsHtml}
            {$sections}
            {$ai}
            {$operations}
            </main>
            <footer>
            <p>{$footer}</p>
            <p>Source labels: <b>detected</b> = read directly from project files; <b>inferred</b> = derived from constraints, defaults or examples; <b>unknown</b> = needs runtime evaluation.</p>
            </footer>
            </body>
            </html>

            HTML;
    }

    private function finding(Finding $finding, int $number): string
    {
        $confidence = $finding->confidence === Confidence::Confirmed ? 'Confirmed' : 'Potential risk, needs review';
        $evidence = $finding->evidence !== '' ? sprintf('<h4>Evidence</h4><pre>%s</pre>', self::e($finding->evidence)) : '';

        return sprintf(
            '<article class="finding sev-%s" id="finding-%d">'
            . '<header><span class="badge sev-%s">%s</span><h3>%d. %s</h3></header>'
            . '<p class="where"><code>%s</code> · %s · %s · <code>%s</code></p>'
            . '<p>%s</p>%s<h4>Remediation</h4><p>%s</p>'
            . '</article>',
            strtolower($finding->severity->value),
            $number,
            strtolower($finding->severity->value),
            self::e($finding->severity->value),
            $number,
            self::e($finding->title),
            self::e($finding->component),
            self::e($confidence),
            self::e($finding->analyzer),
            self::e($finding->id),
            self::e($finding->explanation),
            $evidence,
            self::e($finding->remediation),
        );
    }

    private function section(AnalyzerResult $result): string
    {
        $html = sprintf('<section id="section-%s"><h2>%s</h2>', self::e($result->analyzer), self::e($result->title));
        if ($result->status !== ResultStatus::Completed) {
            $html .= sprintf('<p class="status">Status: %s</p>', self::e($result->status->value));
        }

        if ($result->facts !== []) {
            $html .= '<table class="facts"><thead><tr><th>Item</th><th>Value</th><th>Source</th></tr></thead><tbody>';
            foreach ($result->facts as $fact) {
                $html .= sprintf(
                    '<tr><th scope="row">%s</th><td>%s</td><td><span class="src src-%s">%s</span>%s</td></tr>',
                    self::e($fact->label),
                    self::e($fact->value),
                    self::e($fact->source->value),
                    self::e($fact->source->value),
                    $fact->origin !== null && $fact->origin !== '' ? ' <span class="origin">' . self::e($fact->origin) . '</span>' : '',
                );
            }
            $html .= '</tbody></table>';
        }

        foreach ($result->tables as $table) {
            $html .= sprintf('<h3>%s</h3>', self::e($table->title));
            $html .= $table->isEmpty() ? '<p class="muted">None.</p>' : $this->table($table);
        }

        foreach ($result->notes as $note) {
            $html .= sprintf('<p class="callout">%s</p>', self::e($note));
        }

        return $html . '</section>';
    }

    private function table(Table $table, ?int $codeColumn = null): string
    {
        $html = '<div class="scroll"><table><thead><tr>';
        foreach ($table->headers as $header) {
            $html .= '<th>' . self::e($header) . '</th>';
        }
        $html .= '</tr></thead><tbody>';
        foreach ($table->rows as $row) {
            $html .= '<tr>';
            foreach ($row as $i => $cell) {
                $html .= $i === $codeColumn ? '<td><code>' . self::e($cell) . '</code></td>' : '<td>' . self::e($cell) . '</td>';
            }
            $html .= '</tr>';
        }

        return $html . '</tbody></table></div>';
    }

    private static function e(string $text): string
    {
        return htmlspecialchars($text, ENT_QUOTES | ENT_SUBSTITUTE | ENT_HTML5, 'UTF-8');
    }

