<?php

declare(strict_types=1);

namespace LaraInspect\Reports;

use LaraInspect\Contracts\ReporterInterface;
use LaraInspect\Model\AnalyzerResult;
use LaraInspect\Model\Confidence;
use LaraInspect\Model\Fact;
use LaraInspect\Model\Finding;
use LaraInspect\Model\InspectionReport;
use LaraInspect\Model\ResultStatus;
use LaraInspect\Model\Source;
use LaraInspect\Model\Table;

final class MarkdownReporter implements ReporterInterface
{
    public function format(): string
    {
        return 'markdown';
    }

    public function fileExtension(): string
    {
        return 'md';
    }

    public function render(InspectionReport $report): string
    {
        $out = [];
        $out[] = '# Laravel Project Inspection: ' . self::inline($report->project->name);
        $out[] = '';
        $out[] = '> ' . ReportSummary::readOnlyStatement();
        $out[] = '';
        $out[] = '| | |';
        $out[] = '|---|---|';
        foreach (ReportSummary::metadata($report) as [$label, $value]) {
            $out[] = sprintf('| **%s** | %s |', $label, self::cell($value));
        }
        $out[] = '';

        foreach ($report->project->warnings as $warning) {
            $out[] = '> **Warning:** ' . self::inline($warning);
            $out[] = '';
        }

        $out[] = '## Summary';
        $out[] = '';
        $out[] = ReportSummary::verdict($report);
        $out[] = '';
        $out[] = '| Severity | Count |';
        $out[] = '|---|---:|';
        foreach ($report->severityCounts() as $severity => $count) {
            $out[] = sprintf('| %s | %d |', $severity, $count);
        }
        $out[] = '';

        $findings = $report->findings();
        if ($findings !== []) {
            $out[] = '## Findings';
            $out[] = '';
            $out[] = '| # | Severity | Confidence | Finding | Component |';
            $out[] = '|---:|---|---|---|---|';
            foreach ($findings as $i => $finding) {
                $out[] = sprintf(
                    '| %d | **%s** | %s | [%s](#finding-%d) | `%s` |',
                    $i + 1,
                    $finding->severity->value,
                    $finding->confidence->value,
                    self::cell($finding->title),
                    $i + 1,
                    str_replace('`', "'", $finding->component),
                );
            }
            $out[] = '';
            foreach ($findings as $i => $finding) {
                array_push($out, ...$this->finding($finding, $i + 1));
            }
        }

        foreach ($report->results as $result) {
            array_push($out, ...$this->section($result));
        }

        if ($report->insights !== []) {
            array_push($out, ...$this->insights($report));
        }

        if ($report->audit !== []) {
            $out[] = '## Operations';
            $out[] = '';
            $out[] = 'External commands run during this inspection:';
            $out[] = '';
            $out[] = '| Time | Purpose | Command | Outcome | Network |';
            $out[] = '|---|---|---|---|---|';
            foreach ($report->audit as $entry) {
                $out[] = sprintf(
                    '| %s | %s | `%s` | %s%s | %s |',
                    $entry->timestamp,
                    self::cell($entry->purpose),
                    str_replace('`', "'", $entry->command),
                    $entry->outcome,
                    $entry->exitCode !== null ? ' (exit ' . $entry->exitCode . ')' : '',
                    $entry->network ? 'yes' : 'no',
                );
            }
            $out[] = '';
        }

        $out[] = '---';
        $out[] = '';
        $out[] = sprintf('_Generated by Laravel Project Inspector %s on %s._', $report->inspectorVersion, $report->generatedAt->format(\DateTimeInterface::ATOM));
        $out[] = '';
        $out[] = '_Source labels: **detected** = read directly from project files; **inferred** = derived from constraints, defaults or examples; **unknown** = needs runtime evaluation._';

        return implode("\n", $out) . "\n";
    }

    /**
     * @return list<string>
     */
    private function insights(InspectionReport $report): array
    {
        $out = ['## AI-assisted analysis', ''];
        $out[] = '> **AI-generated content.** Written by a language model from the redacted inspection results above. It can be wrong, and it does not replace the deterministic findings. Verify recommendations before acting on them.';
        $out[] = '';
        foreach ($report->insights as $insight) {
            $out[] = '### ' . self::inline($insight->title);
            $out[] = '';
            $out[] = sprintf('_%s · %s · %s_', self::inline($insight->provider), self::inline($insight->model), self::inline($insight->usage->describe()));
            $out[] = '';
            if ($insight->error !== null) {
                $out[] = '> **Not available:** ' . self::inline($insight->error);
                $out[] = '';
            }
            if ($insight->content !== '') {
                $out[] = self::inline($insight->content);
                $out[] = '';
            }
            foreach ($insight->notes as $note) {
                $out[] = '> ' . self::inline($note);
                $out[] = '';
            }
        }

        return $out;
    }

    /**
     * @return list<string>
     */
    private function finding(Finding $finding, int $number): array
    {
        $out = [];
        $out[] = sprintf('### <a id="finding-%d"></a>%d. [%s] %s', $number, $number, $finding->severity->value, self::inline($finding->title));
        $out[] = '';
        $out[] = sprintf('- **Severity:** %s (%s)', $finding->severity->value, $finding->confidence === Confidence::Confirmed ? 'confirmed' : 'potential risk, needs review');
        $out[] = sprintf('- **Component:** `%s`', str_replace('`', "'", $finding->component));
        $out[] = sprintf('- **Analyzer:** %s · **Rule:** `%s`', $finding->analyzer, $finding->id);
        $out[] = '';
        $out[] = self::inline($finding->explanation);
        $out[] = '';
        if ($finding->evidence !== '') {
            $out[] = '**Evidence**';
            $out[] = '';
            $out[] = '```text';
            $out[] = str_replace('```', "'''", $finding->evidence);
            $out[] = '```';
            $out[] = '';
        }
        $out[] = '**Remediation:** ' . self::inline($finding->remediation);
        $out[] = '';

        return $out;
    }

    /**
     * @return list<string>
     */
    private function section(AnalyzerResult $result): array
    {
        $out = [];
        $out[] = '## ' . self::inline($result->title);
        $out[] = '';
        if ($result->status !== ResultStatus::Completed) {
            $out[] = sprintf('_Status: %s_', $result->status->value);
            $out[] = '';
        }

        if ($result->facts !== []) {
            $out[] = '| Item | Value | Source |';
            $out[] = '|---|---|---|';
            foreach ($result->facts as $fact) {
                $out[] = sprintf('| %s | %s | %s |', self::cell($fact->label), self::cell($fact->value), self::sourceLabel($fact));
            }
            $out[] = '';
        }

        foreach ($result->tables as $table) {
            array_push($out, ...$this->table($table));
        }

        foreach ($result->notes as $note) {
            $out[] = '> ' . self::inline($note);
            $out[] = '';
        }

        return $out;
    }

    /**
     * @return list<string>
     */
    private function table(Table $table): array
    {
        $out = ['### ' . self::inline($table->title), ''];
        if ($table->isEmpty()) {
            return [...$out, '_None._', ''];
        }
        $out[] = '| ' . implode(' | ', array_map(self::cell(...), $table->headers)) . ' |';
        $out[] = '|' . str_repeat('---|', count($table->headers));
        foreach ($table->rows as $row) {
            $out[] = '| ' . implode(' | ', array_map(self::cell(...), $row)) . ' |';
        }
        $out[] = '';

        return $out;
    }

    private static function sourceLabel(Fact $fact): string
    {
        $label = $fact->source === Source::Detected ? 'detected' : '_' . $fact->source->value . '_';

        return $fact->origin !== null && $fact->origin !== '' ? $label . ' (' . self::cell($fact->origin) . ')' : $label;
    }

    /**
     * Escapes text for use inside a table cell.
     */
    private static function cell(string $text): string
    {
        return str_replace(["\r\n", "\n", '|'], ['<br>', '<br>', '\\|'], self::inline($text));
    }

    /**
     * Neutralises raw HTML so report content cannot inject markup into rendered Markdown.
     */
    private static function inline(string $text): string
    {
        return str_replace(['<', '>'], ['&lt;', '&gt;'], $text);
    }
}
