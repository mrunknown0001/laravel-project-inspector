<?php

declare(strict_types=1);

namespace LaraInspect\Tests\Unit\Reports;

use LaraInspect\Model\InspectionReport;
use LaraInspect\Reports\ConsoleReporter;
use LaraInspect\Reports\HtmlReporter;
use LaraInspect\Reports\JsonReporter;
use LaraInspect\Reports\MarkdownReporter;
use LaraInspect\Reports\ReporterRegistry;
use LaraInspect\Tests\Support\SampleReport;
use PHPUnit\Framework\TestCase;
use Symfony\Component\Console\Input\ArrayInput;
use Symfony\Component\Console\Output\BufferedOutput;
use Symfony\Component\Console\Output\OutputInterface;
use Symfony\Component\Console\Style\SymfonyStyle;

final class ReportersTest extends TestCase
{
    public function testJsonIsValidAndLoadsBack(): void
    {
        $json = (new JsonReporter())->render(SampleReport::create());
        $data = json_decode($json, true, 512, JSON_THROW_ON_ERROR);

        self::assertIsArray($data);
        self::assertSame(1, $data['schema_version']);
        self::assertSame('0.1.0', $data['inspector_version']);
        self::assertSame(3, $data['summary']['findings']);
        /** @var array<string, mixed> $data */
        self::assertCount(2, InspectionReport::fromArray($data)->results);
    }

    public function testMarkdownContainsEverySectionAndEscapesContent(): void
    {
        $md = (new MarkdownReporter())->render(SampleReport::create());

        foreach (['# Laravel Project Inspection', '## Summary', '## Findings', '## Environment', '## Dependencies', '## Operations', '### Drivers'] as $heading) {
            self::assertStringContainsString($heading, $md);
        }
        self::assertStringContainsString('| CRITICAL | 1 |', $md);
        self::assertStringContainsString('_inferred_ (framework default)', $md);
        self::assertStringContainsString('a\\|b', $md, 'Pipes inside cells are escaped.');
        self::assertStringContainsString('multi<br>line', $md);
        self::assertStringNotContainsString('<script>', $md);
        self::assertStringContainsString('&lt;script&gt;', $md);
        self::assertStringContainsString("'''", $md, 'Code fences inside evidence cannot close the block.');
        self::assertStringContainsString('Generated by Laravel Project Inspector 0.1.0', $md);
        self::assertStringContainsString('potential risk, needs review', $md);
        self::assertStringContainsString('_None._', $md);
    }

    public function testHtmlIsSelfContainedAndEscaped(): void
    {
        $html = (new HtmlReporter())->render(SampleReport::create());

        self::assertStringStartsWith('<!doctype html>', $html);
        self::assertStringContainsString('<title>Inspection: acme/&lt;shop&gt;</title>', $html);
        self::assertStringNotContainsString('<script', $html);
        self::assertStringContainsString('Title &lt;script&gt;alert(1)&lt;/script&gt;', $html);
        self::assertDoesNotMatchRegularExpression('/(src|href)="https?:/', $html, 'No external resources.');
        self::assertStringContainsString('prefers-color-scheme: dark', $html);
        self::assertStringContainsString('class="finding sev-critical"', $html);
        self::assertStringContainsString('id="section-dependencies"', $html);
        self::assertStringContainsString('<code>composer --version</code>', $html);
        self::assertStringContainsString('Example warning', $html);
    }

    public function testConsoleRendering(): void
    {
        $output = new BufferedOutput(OutputInterface::VERBOSITY_VERBOSE);
        (new ConsoleReporter())->render(SampleReport::create(), new SymfonyStyle(new ArrayInput([]), $output));
        $text = $output->fetch();

        self::assertStringContainsString('Laravel Project Inspector 0.1.0', $text);
        self::assertStringContainsString('CRITICAL', $text);
        self::assertStringContainsString('Title <script>alert(1)</script>', $text, 'Console output shows text literally.');
        self::assertStringContainsString('Fix: Upgrade', $text);
        self::assertStringContainsString('Operations', $text);
        self::assertStringContainsString('immediate attention recommended', $text);
    }

    public function testConsoleTruncatesLongTablesWhenNotVerbose(): void
    {
        $report = SampleReport::create();
        $rows = [];
        for ($i = 0; $i < 30; $i++) {
            $rows[] = ['row' . $i, 'value'];
        }
        $data = $report->toArray();
        $data['results'][0]['tables'][0]['rows'] = $rows;

        $output = new BufferedOutput();
        /** @var array<string, mixed> $data */
        (new ConsoleReporter())->render(InspectionReport::fromArray($data), new SymfonyStyle(new ArrayInput([]), $output));
        $text = $output->fetch();

        self::assertStringContainsString('15 more rows', $text);
        self::assertStringNotContainsString('row20', $text);
        self::assertStringContainsString('Run with -v', $text);
    }

    public function testRegistryNormalisesFormats(): void
    {
        $registry = ReporterRegistry::default();

        self::assertSame(['console', 'markdown', 'html', 'json'], $registry->formats());
        self::assertSame('markdown', $registry->normalise('MD'));
        self::assertSame('console', $registry->normalise('terminal'));
        self::assertSame('html', $registry->get('html')->format());

        $this->expectException(\InvalidArgumentException::class);
        $this->expectExceptionMessage('Unknown format "pdf"');
        $registry->normalise('pdf');
    }
}
